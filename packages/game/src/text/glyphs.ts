/** Every character the font can draw, in sheet order. */
export const FONT_CHARS: string = Object.keys(GLYPHS).join('');

/** The glyph as GLYPH_HEIGHT rows of GLYPH_WIDTH `.`/`#` characters. Throws for a character not in the font. */
export function glyphRows(ch: string): readonly string[] {
  const src = GLYPHS[ch];
  if (src === undefined) throw new Error(`no glyph for ${JSON.stringify(ch)}`);
  const rows = src.split(' ');
  while (rows.length < GLYPH_HEIGHT) rows.push('.'.repeat(GLYPH_WIDTH));
  return rows;
}

export const hasGlyph = (ch: string): boolean => Object.hasOwn(GLYPHS, ch);
